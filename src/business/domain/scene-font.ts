const AVERAGE = 58;

/** The width of a run of text in the same units as its size. */
export function measureText(
  text: string,
  size: number,
  weight: 600 | 700 = 600,
): number {
  const table = ADVANCE[weight];
  let width = 0;
  for (const ch of text) width += table[ch] ?? AVERAGE;
  return (width / 100) * size;
}
