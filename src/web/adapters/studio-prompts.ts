/** Who can do which doings, when not everyone can: from the one list. */
const WHO_CAN = (['person', 'animal'] as Doer[])
  .map((doer) => {
    const cannot = DOINGS.filter((d) => !d.by.includes(doer)).map((d) => d.id);
    return `${doer === 'person' ? 'a person' : 'an animal'} cannot ${cannot.map((id) => `"${id}"`).join(', ')}`;
  })
  .join('; ');

